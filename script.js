let activeLanguage = "en";
const languageStorageKey = "enerstay-language-v3";
const toggle = document.querySelector("[data-lang-toggle]");
const langOptions = document.querySelectorAll("[data-lang-option]");
const nodes = document.querySelectorAll("[data-i18n]");
const engagementForm = document.querySelector("[data-engagement-form]");
const siteHeader = document.querySelector(".site-header");
const menuToggle = document.querySelector("[data-menu-toggle]");
const navLinks = document.querySelectorAll(".nav a");

function renderLanguage(language) {
  activeLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  nodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[language][key]) {
      node.textContent = translations[language][key];
    }
  });
  if (langOptions.length) {
    langOptions.forEach((option) => {
      option.dataset.active = String(option.dataset.langOption === language);
    });
  } else if (toggle) {
    toggle.textContent = language === "zh" ? "EN" : "中";
  }
  localStorage.setItem(languageStorageKey, language);
}

toggle.addEventListener("click", () => {
  renderLanguage(activeLanguage === "zh" ? "en" : "zh");
});

menuToggle?.addEventListener("click", () => {
  const isOpen = siteHeader?.classList.toggle("nav-open") || false;
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    siteHeader?.classList.remove("nav-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  });
});

document.querySelectorAll("[data-order-link]").forEach((link) => {
  link.addEventListener("click", () => {
    const productSelect = document.querySelector('select[name="product"]');
    const productName = link.dataset.product;
    if (!productSelect || !productName) return;
    const matchingOption = Array.from(productSelect.options).find((option) => option.textContent.startsWith(productName));
    if (matchingOption) productSelect.value = matchingOption.value;
  });
});

engagementForm?.querySelector('input[type="date"]')?.setAttribute("min", new Date().toISOString().slice(0, 10));

engagementForm?.addEventListener("submit", async (event) => {
  event.preventDefault();
  const submitButton = engagementForm.querySelector(".form-button");
  const status = engagementForm.querySelector("[data-form-status]");
  engagementForm.classList.add("was-validated");
  if (!engagementForm.checkValidity()) {
    const invalidKey = engagementForm.dataset.invalidKey || "form.invalid";
    if (status) status.textContent = translations[activeLanguage][invalidKey];
    engagementForm.querySelector(":invalid")?.focus();
    return;
  }
  submitButton?.setAttribute("aria-busy", "true");
  if (submitButton) submitButton.disabled = true;
  if (status) status.textContent = "";
  if (submitButton) {
    submitButton.textContent = activeLanguage === "zh" ? submitButton.dataset.busyZh : submitButton.dataset.busyEn;
  }
  const formData = new FormData(engagementForm);
  try {
    const endpoint = engagementForm.action.replace("formsubmit.co/", "formsubmit.co/ajax/");
    const response = await fetch(endpoint, {
      method: "POST",
      headers: { Accept: "application/json" },
      body: formData
    });
    if (!response.ok) throw new Error("Submission failed");
    engagementForm.reset();
    engagementForm.classList.remove("was-validated");
    const successKey = engagementForm.dataset.successKey || "form.success";
    if (status) status.textContent = translations[activeLanguage][successKey];
  } catch (error) {
    if (status) status.textContent = translations[activeLanguage]["form.error"];
  } finally {
    submitButton?.setAttribute("aria-busy", "false");
    if (submitButton) submitButton.disabled = false;
    if (submitButton) {
      submitButton.textContent = activeLanguage === "zh" ? submitButton.dataset.defaultZh : submitButton.dataset.defaultEn;
    }
  }
});

renderLanguage(localStorage.getItem(languageStorageKey) || "en");
